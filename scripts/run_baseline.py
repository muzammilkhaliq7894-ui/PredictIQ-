"""Run Phase 2 baseline modeling and write reproducible evaluation artifacts."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from data.loaders import load_ai4i2020, load_cycle001
from data.validation import validate_ai4i2020, validate_cycle001
from models.baseline import (
    run_ai4i_baselines,
    run_ai4i_model_comparison,
    run_cycle_baseline,
    save_confusion_plot,
    save_cycle_plot,
)

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--contamination", type=float, default=0.01)
    args = parser.parse_args()
    output = ROOT / "reports" / "baseline"
    plots = output / "plots"
    output.mkdir(parents=True, exist_ok=True)
    plots.mkdir(parents=True, exist_ok=True)

    cycle = load_cycle001(ROOT / "docs" / "cycle_001_machine_data.csv")
    ai4i = load_ai4i2020(ROOT / "docs" / "ai4i2020.csv")
    validate_cycle001(cycle)
    validate_ai4i2020(ai4i)

    cycle_results = run_cycle_baseline(cycle, contamination=args.contamination)
    for name, table in cycle_results.items():
        table.to_csv(output / f"cycle001_{name}.csv", index=False)
    cycle_results["scores"].loc[cycle_results["scores"]["alert"]].to_csv(
        output / "cycle001_flagged_timestamps.csv", index=False
    )
    save_cycle_plot(cycle_results["scores"], plots / "cycle001_anomaly_scores.png")

    ai4i_results = run_ai4i_baselines(ai4i)
    for name, table in ai4i_results.items():
        table.to_csv(output / f"ai4i2020_{name}.csv", index=False)
    save_confusion_plot(ai4i_results["confusion_matrices"], plots / "ai4i2020_confusion_matrices.png")
    comparison = run_ai4i_model_comparison(ai4i)
    (output / "ai4i2020_model_comparison.json").write_text(
        json.dumps(comparison, indent=2), encoding="utf-8"
    )

    report = f"""# Phase 2 Baseline Modeling Report

Generated by `python scripts/run_baseline.py` with random seed 42.

## Cycle 001 anomaly detection

Isolation Forest was fit to numeric telemetry only. `Datum/Zeit` and
`Maschinennummer` were excluded as timestamp/identifier fields. Empty and constant
columns were excluded; the audit and correlated sensor pairs are in the CSV artifacts.
The configured contamination is `{args.contamination}` and the observed alert rate is
`{cycle_results["summary"].iloc[0]["alert_rate"]:.2%}`. Higher `anomaly_score` means
more anomalous under this unsupervised model.

The evaluation fits and scores this unsupervised model on the available extract;
there is no labeled holdout or verified anomaly ground truth. These are anomaly
alerts, not confirmed failures, and do not establish failure prediction or advance
warning. A median/MAD top-1% comparator is exposed separately for descriptive alert
overlap only; it is not used as a supervised performance baseline.

## AI4I 2020 classification

The target is the supplied `Machine failure` label. `UDI`, `Product ID`, subtype
metadata (`TWF`, `HDF`, `PWF`, `OSF`, `RNF`), and the target were excluded from
features. `Type` is one-hot encoded; numeric features are standardized inside a
training-only pipeline. A stratified 75/25 split and seed 42 were used.

The 27 rows where the target disagrees with the union of subtype metadata are listed
in `ai4i2020_label_inconsistencies.csv`. Labels were not corrected or dropped.
Dummy, balanced logistic regression, current balanced Random Forest, and a
min-samples-leaf-2 Random Forest candidate are compared using precision, recall, F1,
and average precision. The repeated comparison uses stratified 75/25 holdouts with
seeds 42, 17, and 91; fold-level results, feature lists, estimator parameters, and
scikit-learn version are in `ai4i2020_model_comparison.json`. Preprocessing is fit
inside each training fold. Confusion matrices and class balance are saved separately.
Average precision is the primary ranking metric because the positive class is rare.
The candidate was promoted only after improving both F1 and average precision on all
three holdouts. The reported held-out results are offline evidence, not a live-system
guarantee.

## Limitations

These baselines are offline evaluations on small, static datasets. The Cycle 001
extract has no confirmed anomaly labels, and AI4I is not a temporal maintenance
dataset. Results must not be interpreted as real-world failure prediction, advance
warning, or production performance.
"""
    (output / "BASELINE_REPORT.md").write_text(report, encoding="utf-8")


if __name__ == "__main__":
    main()

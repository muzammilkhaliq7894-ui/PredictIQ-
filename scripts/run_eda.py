"""Run Phase 1 EDA and write reports without fitting any model."""

from pathlib import Path

import pandas as pd

from data.eda import column_profile, numeric_summary, save_ai4i_plots, save_cycle_plots
from data.loaders import load_ai4i2020, load_cycle001
from data.validation import validate_ai4i2020, validate_cycle001


ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
REPORTS = ROOT / "reports"


def main() -> None:
    REPORTS.mkdir(exist_ok=True)
    plots = REPORTS / "plots"
    cycle = load_cycle001(DOCS / "cycle_001_machine_data.csv")
    ai4i = load_ai4i2020(DOCS / "ai4i2020.csv")
    cycle_validation = validate_cycle001(cycle)
    ai4i_validation = validate_ai4i2020(ai4i)

    cycle_profile = column_profile(cycle, "cycle_001")
    ai4i_profile = column_profile(ai4i, "ai4i2020")
    cycle_profile.to_csv(REPORTS / "cycle001_column_profile.csv", index=False)
    ai4i_profile.to_csv(REPORTS / "ai4i2020_column_profile.csv", index=False)
    numeric_summary(cycle, "cycle_001").to_csv(REPORTS / "cycle001_numeric_summary.csv", index=False)
    numeric_summary(ai4i, "ai4i2020").to_csv(REPORTS / "ai4i2020_numeric_summary.csv", index=False)

    ai4i["any_failure_subtype"] = (
        ai4i[["TWF", "HDF", "PWF", "OSF", "RNF"]].sum(axis=1) > 0
    ).astype(int)
    ai4i[["Machine failure", "any_failure_subtype"]].value_counts().rename("rows").reset_index().to_csv(
        REPORTS / "ai4i2020_label_consistency.csv", index=False
    )
    ai4i.groupby("Type", observed=True)["Machine failure"].agg(["count", "sum", "mean"]).reset_index().to_csv(
        REPORTS / "ai4i2020_failure_by_type.csv", index=False
    )
    cycle["Maschinennummer"].value_counts().rename_axis("machine_id").reset_index(name="rows").to_csv(
        REPORTS / "cycle001_machine_coverage.csv", index=False
    )
    cycle["Datum/Zeit"].diff().dt.total_seconds().describe().to_frame("seconds").to_csv(
        REPORTS / "cycle001_sampling_intervals.csv"
    )
    save_cycle_plots(cycle, plots)
    save_ai4i_plots(ai4i, plots)
    _write_report(cycle, ai4i, cycle_validation, ai4i_validation, cycle_profile, ai4i_profile)


def _write_report(cycle, ai4i, cycle_validation, ai4i_validation, cycle_profile, ai4i_profile) -> None:
    subtype_columns = ["TWF", "HDF", "PWF", "OSF", "RNF"]
    mismatch = int(
        (ai4i["Machine failure"] != (ai4i[subtype_columns].sum(axis=1) > 0).astype(int)).sum()
    )
    constants_cycle = cycle_profile.loc[cycle_profile["constant"], "column"].tolist()
    constants_ai4i = ai4i_profile.loc[ai4i_profile["constant"], "column"].tolist()
    report = f"""# Phase 1 EDA Report

Generated by `python scripts/run_eda.py`. Raw datasets under `docs/` were not modified.

## Dataset validation

| Dataset | Rows | Columns after loading | Missing values | Duplicate rows |
|---|---:|---:|---:|---:|
| Cycle 001 | {cycle_validation.rows} | {cycle_validation.columns} | {cycle_validation.missing_values} | {cycle_validation.duplicate_rows} |
| AI4I 2020 | {ai4i_validation.rows} | {ai4i_validation.columns} | {ai4i_validation.missing_values} | {ai4i_validation.duplicate_rows} |

## Cycle 001

- Loaded with semicolon delimiters and comma decimals.
- Completely empty trailing columns were removed by the loader.
- Timestamps parse successfully and are strictly increasing.
- Time range: `{cycle['Datum/Zeit'].min()}` to `{cycle['Datum/Zeit'].max()}`.
- Machine coverage: {cycle['Maschinennummer'].nunique()} machine ID(s), `{cycle['Maschinennummer'].unique().tolist()}`.
- Sampling intervals are approximately 12 ms; see `cycle001_sampling_intervals.csv`.
- Constant columns: {", ".join(constants_cycle) if constants_cycle else "none"}.
- There is no failure or maintenance label. This dataset supports unsupervised anomaly analysis only.

## AI4I 2020

- Contains {len(ai4i)} rows, {ai4i['Type'].nunique()} product types, and {int(ai4i['Machine failure'].sum())} positive `Machine failure` labels.
- Machine failure prevalence is {ai4i['Machine failure'].mean():.2%}; accuracy alone is not an adequate metric.
- Product type counts: {ai4i['Type'].value_counts().to_dict()}.
- The five subtype columns are labels/metadata and must not be model features.
- `Machine failure` disagrees with the union of subtype labels in {mismatch} row(s).
- Constant columns: {", ".join(constants_ai4i) if constants_ai4i else "none"}.

## Label and leakage boundary

Cycle 001 and AI4I 2020 remain independent. No labels are transferred between them.
For future AI4I classification, exclude `UDI`, `Product ID`, `Machine failure`, `TWF`, `HDF`, `PWF`, `OSF`, and `RNF` from the feature matrix.
The primary target is `Machine failure`.

## Limitations

Cycle 001 is a single-machine, short telemetry extract without verified anomaly labels.
AI4I 2020 is highly imbalanced and has no real maintenance timeline or remaining-useful-life target.
These limitations prevent claims about production performance or failure forecasting at this stage.

## Generated artifacts

- `cycle001_column_profile.csv`
- `cycle001_numeric_summary.csv`
- `cycle001_machine_coverage.csv`
- `cycle001_sampling_intervals.csv`
- `ai4i2020_column_profile.csv`
- `ai4i2020_numeric_summary.csv`
- `ai4i2020_failure_by_type.csv`
- `ai4i2020_label_consistency.csv`
- `plots/`
"""
    (REPORTS / "EDA_REPORT.md").write_text(report, encoding="utf-8")


if __name__ == "__main__":
    main()
